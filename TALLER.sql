
USE taller;

CREATE TABLE  Sexo(
    ID_SEXO CHARACTER VARYING(4) NOT NULL,
    SEXO TEXT,
    PRIMARY KEY (ID_SEXO)
);

CREATE TABLE Carrera(
    ID_CARRERA CHARACTER VARYING(4) NOT NULL,
    CARRERA TEXT,
    PRIMARY KEY (ID_CARRERA)
);

CREATE TABLE  Materias(
    ID_MATERIA CHARACTER VARYING(4) NOT NULL,
    MATERIA TEXT,
    PRIMARY KEY (ID_MATERIA)
);


CREATE TABLE  Datos_maestro(
    ID_MAESTRO CHARACTER VARYING(4) NOT NULL,
    NOMBRE TEXT NOT NULL,
    DIRECCIÓN CHARACTER VARYING(10) NOT NULL,
    TELEFONO CHARACTER VARYING(10) NOT NULL,
    ID_SEXO CHARACTER VARYING(4) NOT NULL,
    ID_CARRERA CHARACTER VARYING(4) NOT NULL,
    PRIMARY KEY (ID_MAESTRO),
    FOREIGN KEY (ID_SEXO) REFERENCES Sexo(ID_SEXO),
    FOREIGN KEY (ID_CARRERA) REFERENCES Carrera(ID_CARRERA)
);


CREATE TABLE  Asignacion(
    ID_MAESTRO CHARACTER VARYING(4) NOT NULL,
    ID_MATERIA CHARACTER VARYING(4) NOT NULL,
    FOREIGN KEY (ID_MAESTRO) REFERENCES Datos_maestro(ID_MAESTRO),
    FOREIGN KEY (ID_MATERIA) REFERENCES Materias(ID_MATERIA)
);